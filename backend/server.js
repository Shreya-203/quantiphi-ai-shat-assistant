
const express = require("express");
const cors = require("cors");

const app = express();

app.use(cors());
app.use(express.json());

app.get("/", (req, res) => {
  res.json({ message: "AI Chat Assistant demo backend is running!" });
});

app.post("/api/chat", (req, res) => {
  const { prompt, tone } = req.body;

  if (typeof prompt !== "string" || !prompt.trim()) {
    return res.status(400).json({ error: "Message is required." });
  }

  const question = prompt.trim();
  const style = {
    Professional: "Thank you for your question.",
    Casual: "Hey! Good question.",
    Concise: "In short:",
  };

  let answer;

  if (/\b(hi|hello|hey)\b/i.test(question)) {
    answer = "Hello! Welcome to your AI Chat Assistant. How can I help you?";
  } else if (/\b(your name|who are you)\b/i.test(question)) {
    answer = "I'm your AI Chat Assistant demo. I'm here to help answer questions.";
  } else if (/\b(time|date|today)\b/i.test(question)) {
    answer = `The server's current date and time is ${new Date().toLocaleString()}.`;
  } else if (/\b(help|features)\b/i.test(question)) {
    answer = "This demo supports chat messages, tone selection, and a conversation interface. A real AI provider is needed for general AI-generated answers.";
  } else {
    answer = `You asked: "${question}"\n\n${style[tone] || style.Professional} This is a demo response, not a response generated by an AI model. Connect an AI provider to get intelligent answers to general questions.`;
  }

  res.json({
    reply: answer,
    tone: tone || "Professional",
    demo: true,
  });
});

app.listen(3001, () => {
  console.log("Demo backend running at http://localhost:3001");
});
